#!/usr/bin/env python3
"""Generate the buckler-home mark and TV banner for every colour scheme.

The mark is a disc with a ring at its centre. Each scheme gets its own pair of vector drawables
(`ic_mark_<scheme>.xml`, `banner_<scheme>.xml`); the launcher switches between them with
activity-aliases when the user changes scheme. Each scheme here needs an `AppTheme` entry, a
`markRes` case in LauncherIcon.kt and a manifest alias pair (test_parity checks the names).

Usage: python scripts/gen_icons.py
"""

from __future__ import annotations

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DRAWABLE = ROOT / "launcher/app/src/main/res/drawable"

# scheme: (disc, ring, banner background)
SCHEMES = {
    "buckler": ("468689", "83A598", "0F1B1C"),
    "light": ("8A5A00", "E3C27A", "F7F4EC"),
    "dark": ("D4A84B", "F2D891", "0B0E14"),
    "gruvbox": ("D79921", "FABD2F", "282828"),
    "snes_uk": ("D9363E", "F2C230", "34353B"),
    "snes_us": ("5B4A99", "A98CE6", "34333F"),
    "shield": ("1C1C1C", "76B900", "0A0A0A"),
    "slate": ("497298", "6CB4F2", "1E2229"),
    "velvet": ("74599A", "B88CF4", "211B2D"),
    "ember": ("9C4158", "FF5C8A", "22201A"),
    "tidepool": ("1C6E8B", "31A8D6", "03262F"),
    "fjord": ("5E808C", "8CC4D2", "262C37"),
    "marshmallow": ("7A6699", "C9A4F5", "1A1A29"),
    "neon": ("4F6594", "7FA6F5", "14151E"),
    "graphite": ("376193", "58A2F8", "0E1218"),
    "rosewood": ("8F6F73", "EDB7B3", "1B1824"),
    "saffron": ("936C36", "FFB64F", "0E1118"),
}

# Ring geometry measured from the source art, as fractions of the disc radius.
RING_OUTER = 0.381
RING_INNER = 0.219

HEADER = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/gen_icons.py; edit colours there. -->\n'


def _circle(cx: float, cy: float, r: float) -> str:
    return f"M{cx - r:g},{cy:g} a{r:g},{r:g} 0 1,0 {2 * r:g},0 a{r:g},{r:g} 0 1,0 {-2 * r:g},0 Z"


def _mark(cx: float, cy: float, r: float, disc: str, ring: str) -> str:
    mid = round(r * (RING_OUTER + RING_INNER) / 2, 2)
    width = round(r * (RING_OUTER - RING_INNER), 2)
    return (
        f'    <path android:fillColor="#{disc}" android:pathData="{_circle(cx, cy, r)}" />\n'
        f'    <path android:strokeColor="#{ring}" android:strokeWidth="{width:g}" android:fillColor="#00000000"\n'
        f'        android:pathData="{_circle(cx, cy, mid)}" />\n'
    )


def _vector(width: int, height: int, body: str) -> str:
    return (
        HEADER
        + '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        + f'    android:width="{width}dp" android:height="{height}dp" '
        + f'android:viewportWidth="{width}" android:viewportHeight="{height}">\n'
        + body
        + "</vector>\n"
    )


def write_drawables() -> None:
    for name, (disc, ring, bg) in SCHEMES.items():
        (DRAWABLE / f"ic_mark_{name}.xml").write_text(_vector(100, 100, _mark(50, 50, 48, disc, ring)))
        banner = f'    <path android:fillColor="#{bg}" android:pathData="M0,0 H320 V180 H0 Z" />\n'
        (DRAWABLE / f"banner_{name}.xml").write_text(_vector(320, 180, banner + _mark(160, 90, 62, disc, ring)))


def main() -> None:
    argparse.ArgumentParser(description=__doc__.splitlines()[0]).parse_args()
    write_drawables()


if __name__ == "__main__":
    main()
